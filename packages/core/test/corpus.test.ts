/**
 * @fileoverview End-to-end conformance over `testing/*.grex`.
 *
 * The sample files are the language's only specification, so this suite is what
 * stops them drifting: each one must compile clean under its own flavor, pass its
 * own `test` blocks, and reproduce `testing/EXPECTED.md` byte for byte.
 *
 * EXPECTED.md is generated rather than written by hand. Regenerate it with
 * `GREX_UPDATE_EXPECTED=1 bun test corpus` and read the diff before committing:
 * it is a record of what the compiler does, so an unexpected change there is the
 * point of the file.
 */

import { expect, test } from "bun:test";
import { readdirSync } from "node:fs";
import { join } from "node:path";

import { compile, runTests, type Diagnostic, type FlavorName } from "../index";

const CORPUS = join(import.meta.dir, "..", "..", "..", "testing");
const EXPECTED = join(CORPUS, "EXPECTED.md");
const OTHER_FLAVORS: FlavorName[] = ["js", "re2"];

const samples = readdirSync(CORPUS)
    .filter((name) => name.endsWith(".grex") || name.endsWith(".grex.txt"))
    .sort();

const sources = new Map<string, string>();
for (const name of samples) sources.set(name, await Bun.file(join(CORPUS, name)).text());

function errorsOf(diagnostics: readonly Diagnostic[]): readonly Diagnostic[] {
    return diagnostics.filter((d) => d.severity === "error");
}

test("the corpus is not empty", () => {
    // A silent pass over no files would make every other test here vacuous.
    expect(samples.length).toBeGreaterThan(0);
});

for (const name of samples) {
    const source = sources.get(name)!;

    test(`${name} compiles clean under its own flavor`, () => {
        const { diagnostics, patterns } = compile(source);
        const errors = errorsOf(diagnostics).map((d) => `${d.start.line}:${d.start.column} ${d.message}`);

        expect(errors).toEqual([]);
        expect(patterns!.length).toBeGreaterThan(0);
    });

    test(`${name} emits regexes the JS engine accepts`, () => {
        // A pattern using something JS lacks is excluded by its own flavor report,
        // so anything that does compile for js must also be a valid RegExp.
        const { diagnostics, patterns } = compile(source, { flavor: "js" });
        if (errorsOf(diagnostics).length > 0) return;

        for (const pattern of patterns!)
            expect(() => new RegExp(pattern.source, pattern.flags)).not.toThrow();
    });

    test(`${name} passes its own test blocks`, () => {
        const { diagnostics, results } = runTests(source);

        expect(errorsOf(diagnostics)).toEqual([]);
        const notPassing = results
            .filter((r) => r.status !== "pass")
            .map((r) => `${r.pattern} ${r.mode} ${JSON.stringify(r.subject)}: ${r.status} — ${r.detail}`);

        expect(notPassing).toEqual([]);
    });
}

test("EXPECTED.md matches what the compiler produces", async () => {
    const generated = report();

    if (process.env.GREX_UPDATE_EXPECTED) {
        await Bun.write(EXPECTED, generated);
        return;
    }

    const committed = await Bun.file(EXPECTED)
        .text()
        .catch(() => null);

    if (committed === null)
        throw new Error("testing/EXPECTED.md is missing; run GREX_UPDATE_EXPECTED=1 bun test corpus");

    expect(generated).toBe(committed);
});

/** The whole corpus as markdown: the regexes, the tests, and the flavor limits. */
function report(): string {
    const out: string[] = [
        "<!-- Generated by `GREX_UPDATE_EXPECTED=1 bun test corpus`. Do not edit by hand. -->",
        "",
        "# EXPECTED",
        "",
        "What the g-rex compiler produces for every sample in `testing/`. This file is",
        "the record the corpus test compares against, so a change here is a change in",
        "compiler behaviour and wants reading before it is committed.",
    ];

    for (const name of samples) {
        const source = sources.get(name)!;
        const { patterns } = compile(source);

        out.push("", `## ${name}`, "");

        if (!patterns) {
            out.push("Does not compile under its own flavor.");
            continue;
        }

        for (const pattern of patterns) {
            out.push(`### pattern ${pattern.name}`, "");
            if (pattern.docs) out.push(`> ${pattern.docs.replace(/\s+/g, " ").trim()}`, "");
            out.push("```re", `${pattern.source}`, "```", "");
            out.push(`Flags: \`${pattern.flags || "(none)"}\``);
            out.push(
                `Groups: ${
                    pattern.captures.length === 0
                        ? "none"
                        : pattern.captures
                              .map((capture, i) => `${i + 1} ${capture === null ? "(unnamed)" : `\`${capture}\``}`)
                              .join(", ")
                }`,
            );
            out.push("");
        }

        const { results } = runTests(source);
        out.push("### tests", "");
        if (results.length === 0) out.push("None.", "");
        for (const result of results)
            out.push(
                `- ${result.status} — \`${result.pattern}\` ${result.mode} ${inlineCode(result.subject)}` +
                    (result.detail ? `: ${result.detail}` : ""),
            );
        if (results.length > 0) out.push("");

        // The reason `@flavor` exists: the same source is not portable, and this
        // is the list of what each other flavor refuses, line by line.
        for (const flavor of OTHER_FLAVORS) {
            const errors = errorsOf(compile(source, { flavor }).diagnostics);
            out.push(`### under \`${flavor}\``, "");
            if (errors.length === 0) {
                out.push("Compiles unchanged.", "");
                continue;
            }
            for (const error of [...errors].sort(byPosition))
                out.push(`- line ${error.start.line}: ${error.message.replace(/^The \w+ flavor cannot express this: /, "")}`);
            out.push("");
        }
    }

    return `${out.join("\n").trimEnd()}\n`;
}

function byPosition(a: Diagnostic, b: Diagnostic): number {
    return a.start.line - b.start.line || a.start.column - b.start.column;
}

/** Inline code for a subject that may itself contain backticks. */
function inlineCode(text: string): string {
    const fence = text.includes("`") ? "``" : "`";
    return `${fence}${text}${fence}`;
}
